CREATE TABLE projects (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(20)   NOT NULL UNIQUE,
    owner_id               BIGINT        NOT NULL REFERENCES users(id),
    plot_id                BIGINT        REFERENCES plots(id),
    sector                 VARCHAR(30)   NOT NULL,
    use_case               VARCHAR(30),
    district               VARCHAR(30),
    title                  VARCHAR(160)  NOT NULL,
    tagline                VARCHAR(240),
    problem                TEXT,
    solution               TEXT,
    market                 TEXT,
    team                   TEXT,
    stage                  VARCHAR(20)   NOT NULL,
    scale                  DECIMAL(14,2),
    capex                  DECIMAL(16,2) NOT NULL,
    own_funds              DECIMAL(16,2) NOT NULL DEFAULT 0,
    ask_amount             DECIMAL(16,2) NOT NULL,
    deal_type              VARCHAR(20)   NOT NULL,
    equity_percent         DECIMAL(5,2),
    interest_percent       DECIMAL(5,2),
    revenue_share_percent  DECIMAL(5,2),
    claimed_revenue        DECIMAL(16,2),
    claimed_profit         DECIMAL(16,2),
    claimed_yield          DECIMAL(12,3),
    claimed_price          DECIMAL(12,2),
    jobs                   INT           NOT NULL DEFAULT 0,
    status                 VARCHAR(20)   NOT NULL,
    verified               BOOLEAN       NOT NULL DEFAULT FALSE,
    views                  INT           NOT NULL DEFAULT 0,
    created_at             TIMESTAMP     NOT NULL,
    updated_at             TIMESTAMP     NOT NULL,
    version                BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_projects_status_sector ON projects(status, sector);

CREATE TABLE project_interests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT        NOT NULL REFERENCES projects(id),
    investor_id  BIGINT        NOT NULL REFERENCES users(id),
    amount       DECIMAL(16,2) NOT NULL,
    message      TEXT,
    status       VARCHAR(20)   NOT NULL,
    reply        TEXT,
    created_at   TIMESTAMP     NOT NULL,
    updated_at   TIMESTAMP     NOT NULL,
    CONSTRAINT uq_interest UNIQUE (project_id, investor_id)
);

CREATE TABLE investor_profiles (
    user_id        BIGINT        PRIMARY KEY REFERENCES users(id),
    sectors        VARCHAR(400),
    ticket_min     DECIMAL(16,2),
    ticket_max     DECIMAL(16,2),
    risk           VARCHAR(10),
    horizon_years  INT,
    updated_at     TIMESTAMP     NOT NULL
);

CREATE TABLE buyer_demands (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)   NOT NULL UNIQUE,
    buyer_id        BIGINT        NOT NULL REFERENCES users(id),
    company         VARCHAR(160)  NOT NULL,
    buyer_type      VARCHAR(20)   NOT NULL,
    product         VARCHAR(30)   NOT NULL,
    category        VARCHAR(30)   NOT NULL,
    volume_tons     DECIMAL(12,2) NOT NULL,
    price_min       DECIMAL(12,2),
    price_max       DECIMAL(12,2),
    contract_years  INT           NOT NULL,
    district        VARCHAR(30)   NOT NULL,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    radius_km       INT           NOT NULL,
    quality         TEXT,
    season          VARCHAR(80),
    status          VARCHAR(20)   NOT NULL,
    verified_by     BIGINT        REFERENCES users(id),
    verified_at     TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_demands_status_category ON buyer_demands(status, category);

CREATE TABLE letters_of_intent (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id       BIGINT        NOT NULL REFERENCES buyer_demands(id),
    requester_id    BIGINT        NOT NULL REFERENCES users(id),
    plot_id         BIGINT        REFERENCES plots(id),
    application_id  BIGINT        REFERENCES applications(id),
    project_id      BIGINT        REFERENCES projects(id),
    volume_tons     DECIMAL(12,2) NOT NULL,
    price           DECIMAL(12,2),
    status          VARCHAR(20)   NOT NULL,
    message         TEXT,
    buyer_note      TEXT,
    signed_at       TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL,
    updated_at      TIMESTAMP     NOT NULL
);
