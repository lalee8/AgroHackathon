CREATE TABLE equipment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT        NOT NULL REFERENCES users(id),
    type          VARCHAR(30)   NOT NULL,
    title         VARCHAR(160)  NOT NULL,
    district      VARCHAR(30)   NOT NULL,
    price         DECIMAL(12,2) NOT NULL,
    price_unit    VARCHAR(10)   NOT NULL,
    season_from   INT,
    season_to     INT,
    suitable      VARCHAR(200),
    description   VARCHAR(600),
    made_year     INT,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL
);
CREATE INDEX ix_equipment_district ON equipment(district);

CREATE TABLE equipment_requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id  BIGINT        NOT NULL REFERENCES equipment(id) ON DELETE CASCADE,
    requester_id  BIGINT        NOT NULL REFERENCES users(id),
    plot_id       BIGINT        REFERENCES plots(id),
    start_date    DATE          NOT NULL,
    quantity      DECIMAL(10,2) NOT NULL,
    message       VARCHAR(500),
    total_price   DECIMAL(14,2) NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    created_at    TIMESTAMP     NOT NULL,
    decided_at    TIMESTAMP
);
CREATE INDEX ix_eqreq_equipment ON equipment_requests(equipment_id);
CREATE INDEX ix_eqreq_requester ON equipment_requests(requester_id);
