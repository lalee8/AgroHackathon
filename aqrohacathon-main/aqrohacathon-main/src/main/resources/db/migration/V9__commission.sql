-- Müsabiqə komissiyası: dövlət qurumlarının nümayəndələri və onların müraciətlər üzrə səsləri

CREATE TABLE commission_members (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    VARCHAR(160) NOT NULL,
    position     VARCHAR(200),
    institution  VARCHAR(20)  NOT NULL,
    member_role  VARCHAR(20)  NOT NULL,
    user_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    sort_order   INT          NOT NULL DEFAULT 0
);

CREATE TABLE commission_votes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT       NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    member_id       BIGINT       NOT NULL REFERENCES commission_members(id) ON DELETE CASCADE,
    vote            VARCHAR(10)  NOT NULL,
    comment         VARCHAR(600),
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_commission_vote UNIQUE (application_id, member_id)
);

CREATE INDEX ix_commission_votes_app ON commission_votes(application_id);
