-- =====================================================================
--  AqroInvest Qarabağ — əsas məlumat modeli (PostgreSQL / H2 uyğun)
--  Obyektlər: istifadəçi, təsərrüfat sahəsi, müsabiqə, müraciət
--  EKTİS inteqrasiyası üçün: integration_events (transactional outbox)
-- =====================================================================

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(160) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    full_name       VARCHAR(160) NOT NULL,
    phone           VARCHAR(30),
    fin             VARCHAR(7),
    role            VARCHAR(20)  NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_logins   INT          NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP,
    last_login_at   TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL
);

CREATE TABLE plots (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(20)   NOT NULL UNIQUE,
    name                  VARCHAR(160)  NOT NULL,
    district              VARCHAR(30)   NOT NULL,
    village               VARCHAR(80),
    category              VARCHAR(30)   NOT NULL,
    area_ha               DECIMAL(10,2) NOT NULL,
    latitude              DOUBLE PRECISION NOT NULL,
    longitude             DOUBLE PRECISION NOT NULL,
    polygon               TEXT,
    soil_type             VARCHAR(80),
    soil_quality          INT,
    water_source          VARCHAR(120),
    irrigation            BOOLEAN       NOT NULL DEFAULT FALSE,
    road_distance_km      DECIMAL(6,2),
    electricity           BOOLEAN       NOT NULL DEFAULT FALSE,
    gas                   BOOLEAN       NOT NULL DEFAULT FALSE,
    altitude_m            INT,
    slope_percent         DECIMAL(4,1),
    demining_status       VARCHAR(20)   NOT NULL,
    demining_certificate  VARCHAR(40),
    usage_type            VARCHAR(20)   NOT NULL,
    lease_years           INT           NOT NULL,
    annual_rent_per_ha    DECIMAL(10,2) NOT NULL,
    min_investment        DECIMAL(14,2) NOT NULL,
    min_jobs              INT           NOT NULL,
    recommended_crops     TEXT,
    description           TEXT,
    terms                 TEXT,
    status                VARCHAR(20)   NOT NULL,
    created_at            TIMESTAMP     NOT NULL,
    updated_at            TIMESTAMP     NOT NULL,
    version               BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_plots_district ON plots(district);
CREATE INDEX idx_plots_category ON plots(category);
CREATE INDEX idx_plots_status   ON plots(status);

CREATE TABLE competitions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(30)  NOT NULL UNIQUE,
    title          VARCHAR(200) NOT NULL,
    description    TEXT,
    start_at       TIMESTAMP    NOT NULL,
    deadline_at    TIMESTAMP    NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    criteria       TEXT,
    created_by     BIGINT REFERENCES users(id),
    approved_by    BIGINT REFERENCES users(id),
    approved_at    TIMESTAMP,
    review_note    TEXT,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL
);
CREATE INDEX idx_competitions_status ON competitions(status);

CREATE TABLE competition_plots (
    competition_id BIGINT NOT NULL REFERENCES competitions(id) ON DELETE CASCADE,
    plot_id        BIGINT NOT NULL REFERENCES plots(id),
    PRIMARY KEY (competition_id, plot_id)
);

CREATE SEQUENCE application_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE applications (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_number               VARCHAR(30) UNIQUE,
    tracking_code            VARCHAR(12) NOT NULL,
    applicant_id             BIGINT       NOT NULL REFERENCES users(id),
    competition_id           BIGINT       NOT NULL REFERENCES competitions(id),
    plot_id                  BIGINT       NOT NULL REFERENCES plots(id),
    applicant_type           VARCHAR(10)  NOT NULL,
    company_name             VARCHAR(200),
    voen                     VARCHAR(10),
    fin                      VARCHAR(7),
    contact_phone            VARCHAR(30),
    contact_email            VARCHAR(160),
    legal_address            VARCHAR(255),
    activity_type            VARCHAR(30),
    investment_amount        DECIMAL(14,2),
    own_funds_percent        INT,
    jobs_planned             INT,
    implementation_months    INT,
    experience_years         INT,
    technologies             TEXT,
    business_plan            TEXT,
    expected_annual_revenue  DECIMAL(14,2),
    idp_status               BOOLEAN      NOT NULL DEFAULT FALSE,
    consent_given            BOOLEAN      NOT NULL DEFAULT FALSE,
    status                   VARCHAR(30)  NOT NULL,
    decision                 VARCHAR(20),
    decision_note            TEXT,
    auto_score               INT,
    score_breakdown          TEXT,
    ektis_farmer_status      VARCHAR(30),
    ektis_reference          VARCHAR(40),
    submitted_at             TIMESTAMP,
    decided_at               TIMESTAMP,
    created_at               TIMESTAMP    NOT NULL,
    updated_at               TIMESTAMP    NOT NULL,
    version                  BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX idx_app_applicant   ON applications(applicant_id);
CREATE INDEX idx_app_competition ON applications(competition_id);
CREATE INDEX idx_app_status      ON applications(status);

CREATE TABLE application_status_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT      NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    from_status     VARCHAR(30),
    to_status       VARCHAR(30) NOT NULL,
    comment         TEXT,
    actor_id        BIGINT REFERENCES users(id),
    actor_name      VARCHAR(160),
    created_at      TIMESTAMP   NOT NULL
);
CREATE INDEX idx_hist_app ON application_status_history(application_id);

CREATE TABLE application_documents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT       NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    doc_type        VARCHAR(30)  NOT NULL,
    original_name   VARCHAR(255) NOT NULL,
    stored_name     VARCHAR(80)  NOT NULL,
    content_type    VARCHAR(100) NOT NULL,
    size_bytes      BIGINT       NOT NULL,
    sha256          VARCHAR(64)  NOT NULL,
    uploaded_by     BIGINT REFERENCES users(id),
    uploaded_at     TIMESTAMP    NOT NULL
);
CREATE INDEX idx_docs_app ON application_documents(application_id);

CREATE TABLE evaluations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT    NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    expert_id       BIGINT    NOT NULL REFERENCES users(id),
    scores          TEXT      NOT NULL,
    total           INT       NOT NULL,
    comment         TEXT,
    created_at      TIMESTAMP NOT NULL,
    UNIQUE (application_id, expert_id)
);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type        VARCHAR(30)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    message     TEXT,
    link        VARCHAR(255),
    is_read     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL
);
CREATE INDEX idx_notif_user ON notifications(user_id, is_read);

CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     BIGINT,
    actor_email  VARCHAR(160),
    action       VARCHAR(60)  NOT NULL,
    entity_type  VARCHAR(40),
    entity_id    VARCHAR(40),
    details      TEXT,
    ip_address   VARCHAR(45),
    created_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_audit_created ON audit_logs(created_at);

-- Transactional Outbox: EKTİS-ə göndəriləcək hadisələr eyni tranzaksiyada yazılır,
-- sonra fon prosesi ilə təkrar cəhd (exponential backoff) və idempotentlik açarı ilə ötürülür.
CREATE TABLE integration_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         VARCHAR(36)  NOT NULL UNIQUE,
    event_type       VARCHAR(60)  NOT NULL,
    aggregate_type   VARCHAR(40)  NOT NULL,
    aggregate_id     VARCHAR(40)  NOT NULL,
    payload          TEXT         NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    attempts         INT          NOT NULL DEFAULT 0,
    last_error       TEXT,
    external_ref     VARCHAR(60),
    next_attempt_at  TIMESTAMP    NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    sent_at          TIMESTAMP
);
CREATE INDEX idx_events_status ON integration_events(status, next_attempt_at);
