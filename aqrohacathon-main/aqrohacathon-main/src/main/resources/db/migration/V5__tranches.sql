ALTER TABLE project_interests ADD accepted_at TIMESTAMP;
UPDATE project_interests SET accepted_at = updated_at WHERE status = 'ACCEPTED';

CREATE TABLE tranche_releases (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interest_id  BIGINT        NOT NULL REFERENCES project_interests(id) ON DELETE CASCADE,
    seq          INT           NOT NULL,
    amount       DECIMAL(16,2) NOT NULL,
    evidence     TEXT,
    released_by  BIGINT        REFERENCES users(id),
    released_at  TIMESTAMP     NOT NULL,
    CONSTRAINT uq_tranche_release UNIQUE (interest_id, seq)
);
